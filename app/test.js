const I = require("./inventory.js");
const fs = require("fs");
const sample = fs.readFileSync(__dirname + "/../sample/projects.sample.json", "utf8");
let fail = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : JSON.stringify(got) + " != " + JSON.stringify(want)); };
const now = "2026-10-27T00:00:00Z";
const { rows, skipped } = I.parse(sample);
eq("sample has 6 projects", rows.length, 6);
eq("nothing skipped", skipped, []);
eq("bare array accepted", I.parse(JSON.stringify(rows)).rows.length, 6);
eq("garbage rejected", (() => { try { I.parse("{oops"); } catch (e) { return /Not valid JSON/.test(e.message); } })(), true);
eq("wrong shape rejected", (() => { try { I.parse('{"a":1}'); } catch (e) { return /Expected/.test(e.message); } })(), true);
eq("incomplete row skipped and reported", I.parse('[{"ref":"a","name":"x"}]').skipped.length, 1);
const plans = { "org-a": "free", "org-b": "pro" };
const res = I.analyze(rows, plans, now);
const a = res.find((o) => o.id === "org-a"), b = res.find((o) => o.id === "org-b"), c = res.find((o) => o.id === "org-c");
eq("free org cost 0", a.monthly, 0);
eq("pro org: 3 active -> 25 + (30-10)", b.monthly, 45);
eq("unknown plan has no cost and a warning", [c.monthly, c.warnings.length], [null, 1]);
eq("free org over limit warns", I.analyze([...rows, { ref: "z1", name: "z1", organization_id: "org-a", status: "ACTIVE_HEALTHY", created_at: "2026-10-01T00:00:00Z", region: "x" }, { ref: "z2", name: "z2", organization_id: "org-a", status: "ACTIVE_HEALTHY", created_at: "2026-10-01T00:00:00Z", region: "x" }], plans, now).find((o) => o.id === "org-a").warnings.length, 1);
const dorm = res.flatMap((o) => o.projects).filter((p) => p.flags.includes("dormant candidate")).map((p) => p.name);
eq("dormant candidates = paused and >= 90 days old", dorm, ["legacy-poc"]);
eq("young paused project is not a dormant candidate", res.flatMap((o) => o.projects).find((p) => p.name === "new-experiment").flags, ["paused"]);
eq("age in days", res.flatMap((o) => o.projects).find((p) => p.name === "legacy-poc").ageDays, 228);
process.exit(fail ? 1 : 0);
